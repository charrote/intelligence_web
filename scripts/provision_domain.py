#!/usr/bin/env python3
"""Provision / deprovision a dynamic domain.

Usage (host side):
    python3 scripts/provision_domain.py create <slug> --name "采购情报" \
        [--port 8770] [--theme-color "#2a7d4f"] [--description "..."] \
        [--ttl-days 90] [--no-start]

    python3 scripts/provision_domain.py archive <slug>   # soft-delete: stop + archive data
    python3 scripts/provision_domain.py restore <slug>   # restore an archived domain
    python3 scripts/provision_domain.py list

The web admin API (core/app.py) marks registry entries as pending_start /
pending_stop; scripts/domain_watcher.py polls and performs the docker
compose up/down + data archival. This script is the host-side CLI equivalent
(doing the work immediately) and is also used by the watcher.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOMAINS_DIR = os.path.join(REPO_ROOT, "domains")
COMPOSE_DIR = os.path.join(REPO_ROOT, "compose.d")
NGINX_DYNAMIC = os.path.join(REPO_ROOT, "nginx", "dynamic")
REGISTRY = os.path.join(REPO_ROOT, "config", "domains.json")
BACKUP_ROOT = os.path.join(REPO_ROOT, "backups")
PORT_RANGE = range(8770, 8800)
SLUG_RE = re.compile(r"^[a-z][a-z0-9_]{2,31}$")

GENERIC_IMAGE = "intelligence-web-domain-generic:latest"


def log(msg):
    print(f"[domain-provision] {msg}", flush=True)


def load_registry():
    with open(REGISTRY, "r", encoding="utf-8") as f:
        return json.load(f)


def save_registry(data):
    tmp = REGISTRY + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    os.replace(tmp, REGISTRY)


def find_free_port(registry):
    used = set()
    for d in registry.get("domains", []):
        if d.get("status") != "archived":
            used.add(d.get("port"))
    ports_file = os.path.join(REPO_ROOT, "config", "ports.json")
    try:
        with open(ports_file, "r", encoding="utf-8") as f:
            for svc in json.load(f).get("services", {}).values():
                used.add(svc.get("port"))
    except Exception:
        pass
    for p in PORT_RANGE:
        if p not in used:
            return p
    raise SystemExit("No free port in range %d-%d" % (PORT_RANGE.start, PORT_RANGE.stop - 1))


def validate_spec_fields(spec):
    """Whitelist-only validation: spec is data, never code."""
    allowed = {
        "slug", "port", "title_prefix", "scout_label", "agent_names",
        "theme_color", "inbox_rel", "db_filename", "domain_key",
        "statuses", "extra_columns", "list_columns", "search",
        "intelligence_ttl_days", "default_entities", "default_data_sources",
        "target_types", "target_type_initial_data",
    }
    unknown = set(spec.keys()) - allowed
    if unknown:
        raise SystemExit(f"Unknown spec fields: {sorted(unknown)}")
    if not SLUG_RE.match(spec["slug"]):
        raise SystemExit(f"Invalid slug: {spec['slug']} (need ^[a-z][a-z0-9_]{{2,31}}$)")
    if not (1024 <= spec.get("port", 0) <= 65535):
        raise SystemExit(f"Invalid port: {spec.get('port')}")


def render_compose_fragment(slug, port, db_filename, domain_key, ttl):
    """Compose fragment for one dynamic domain (standalone file, joined to the
    main compose's external network so the gateway can resolve domain_<slug>)."""
    return f"""# Auto-generated by scripts/provision_domain.py — do not edit by hand.
# Domain: {slug}
services:
  domain_{slug}:
    image: {GENERIC_IMAGE}
    ports:
      - "{port}:{port}"
    networks:
      - intelligence_web_default
    environment:
      - JWT_SECRET=${{JWT_SECRET:-30debd9f935044badf90a5130ba86c0ccacbf0e9d3e1fd031f20fe0885c1ef08}}
      - CORS_ORIGINS=https://intelligence.nat.ywapi.com,http://intelligence.nat.ywapi.com,http://localhost:8765
      - ANALYZER_DB_SLUG={db_filename}
      - DOMAIN_KEY={domain_key}
      - DOMAIN_SPEC_PATH=/app/spec.json
    command: >
      bash -c "
        cd /app && python -m core.scheduler &
        cd /app && gunicorn -w 2 -b 0.0.0.0:{port} --timeout 120 wsgi:app
      "
    volumes:
      - ${{REPO_HOST}}/domains/{slug}/data:/app/data
      - ${{REPO_HOST}}/domains/{slug}/spec.json:/app/spec.json:ro
      - ${{REPO_HOST}}/config:/app/config
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:{port}/api/health"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 30s
    restart: unless-stopped

networks:
  intelligence_web_default:
    external: true
"""


def render_nginx_conf(slug, port):
    return f"""# Auto-generated by scripts/provision_domain.py — do not edit by hand.
# Domain: {slug} (port {port})
location /d/{slug}/ {{
    auth_request /_auth;
    error_page 401 = @api_auth_fail;
    rewrite ^/d/{slug}/(.*)$ /$1 break;
    proxy_pass http://domain_{slug}:{port};
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header Authorization $http_authorization;
    client_max_body_size 50m;
    proxy_request_buffering off;
    proxy_read_timeout 120s;
}}
"""


def provision_create(args):
    slug = args.slug
    registry = load_registry()
    existing = [d for d in registry["domains"] if d["slug"] == slug]
    if existing and existing[0].get("status") != "archived":
        raise SystemExit(f"Domain '{slug}' already exists and is not archived")

    port = args.port or find_free_port(registry)
    db_filename = f"intelligence_{slug}" if not slug.startswith("intelligence") else slug
    domain_key = slug.replace("intelligence_", "").replace("_", "-")
    ttl = {"default": args.ttl_days}

    spec = {
        "slug": slug,
        "port": port,
        "title_prefix": args.title or args.name or slug,
        "scout_label": f"{args.name or slug}采集",
        "agent_names": [],
        "theme_color": args.theme_color or "#3b4f8c",
        "db_filename": db_filename,
        "domain_key": domain_key,
        "inbox_rel": f"../inbox/",
        "statuses": [
            ("pending", "待核实"),
            ("active", "处理中"),
            ("done", "已完成"),
        ],
        "list_columns": ["id", "title", "status", "date"],
        "search": {
            "engine": "meilisearch",
            "url": "http://meilisearch:7700",
            "api_key": "intel-search-key",
        },
        "intelligence_ttl_days": ttl,
    }
    validate_spec_fields(spec)

    # 1. spec + data dir
    ddir = os.path.join(DOMAINS_DIR, slug)
    os.makedirs(os.path.join(ddir, "data"), exist_ok=True)
    with open(os.path.join(ddir, "spec.json"), "w", encoding="utf-8") as f:
        json.dump(spec, f, ensure_ascii=False, indent=2)
    log(f"spec.json written: {os.path.join(ddir, 'spec.json')}")

    # 2. compose fragment
    os.makedirs(COMPOSE_DIR, exist_ok=True)
    frag = os.path.join(COMPOSE_DIR, f"domain-{slug}.yml")
    with open(frag, "w", encoding="utf-8") as f:
        f.write(render_compose_fragment(slug, port, db_filename, domain_key, ttl))
    log(f"compose fragment written: {frag}")

    # 3. nginx conf
    os.makedirs(NGINX_DYNAMIC, exist_ok=True)
    with open(os.path.join(NGINX_DYNAMIC, f"{slug}.conf"), "w", encoding="utf-8") as f:
        f.write(render_nginx_conf(slug, port))
    log(f"nginx conf written: {os.path.join(NGINX_DYNAMIC, f'{slug}.conf')}")

    # 4. registry entry
    entry = {
        "slug": slug,
        "port": port,
        "name": args.name or args.title or slug,
        "title_prefix": spec["title_prefix"],
        "theme_color": spec["theme_color"],
        "description": args.description or "",
        "enabled": True,
        "dynamic": True,
        "status": "pending_start",
        "db_filename": db_filename,
        "domain_key": domain_key,
        "gateway_prefix": f"/d/{slug}",
    }
    registry["domains"] = [d for d in registry["domains"] if d["slug"] != slug]
    registry["domains"].append(entry)
    save_registry(registry)
    log(f"registry updated: {slug} (port {port}, status pending_start)")

    if not args.no_start:
        start_domain(slug, port)


def _compose_env():
    """Env for docker compose: REPO_HOST lets fragment files use
    ${REPO_HOST}/... absolute volume paths (resolved on the host)."""
    return dict(os.environ, REPO_HOST=REPO_ROOT)


def start_domain(slug, port):
    frag = os.path.join(COMPOSE_DIR, f"domain-{slug}.yml")
    log(f"starting container: docker compose -f {frag} up -d")
    r = subprocess.run(
        ["docker", "compose", "-p", f"domain_{slug}", "--project-directory", REPO_ROOT, "-f", frag, "up", "-d"],
        capture_output=True, text=True, cwd=REPO_ROOT, env=_compose_env(),
    )
    if r.returncode != 0:
        log(f"compose up failed:\n{r.stderr}")
        raise SystemExit("compose up failed")
    # health check
    for _ in range(30):
        h = subprocess.run(
            ["curl", "-sf", f"http://localhost:{port}/api/health"],
            capture_output=True, text=True,
        )
        if h.returncode == 0:
            log(f"domain {slug} is healthy on port {port}")
            return
        time.sleep(2)
    raise SystemExit(f"domain {slug} did not become healthy within 60s")


def stop_container(slug):
    frag = os.path.join(COMPOSE_DIR, f"domain-{slug}.yml")
    if os.path.exists(frag):
        subprocess.run(
            ["docker", "compose", "-p", f"domain_{slug}", "--project-directory", REPO_ROOT, "-f", frag, "down", "--remove-orphans"],
            capture_output=True, text=True, cwd=REPO_ROOT, env=_compose_env(),
        )


def delete_meili_index(db_filename):
    """Delete the Meilisearch index for a domain (best-effort)."""
    import urllib.request
    index_name = f"intelligence_{db_filename}"
    try:
        req = urllib.request.Request(
            f"http://localhost:7700/indexes/{index_name}",
            method="DELETE",
            headers={"Authorization": "Bearer intel-search-key"},
        )
        urllib.request.urlopen(req, timeout=5)
        log(f"meilisearch index deleted: {index_name}")
    except Exception as e:
        log(f"meilisearch index delete skipped ({e})")


def provision_archive(args):
    slug = args.slug
    registry = load_registry()
    entry = next((d for d in registry["domains"] if d["slug"] == slug), None)
    if entry is None:
        raise SystemExit(f"Domain '{slug}' not found")
    if not entry.get("dynamic"):
        raise SystemExit("Legacy domains (research/sales) cannot be archived via this path")
    if entry.get("status") == "archived":
        raise SystemExit(f"Domain '{slug}' is already archived")

    port = entry["port"]
    db_filename = entry.get("db_filename", slug)

    # 1. stop container
    stop_container(slug)

    # 2. archive data dir
    ddir = os.path.join(DOMAINS_DIR, slug)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    archive_dir = os.path.join(BACKUP_ROOT, "domain_archived", f"{slug}_{stamp}")
    os.makedirs(archive_dir, exist_ok=True)
    if os.path.exists(ddir):
        shutil.move(ddir, archive_dir)
        log(f"data archived to: {archive_dir}")

    # 3. remove nginx conf (gateway reloads on restart; watcher can trigger)
    conf = os.path.join(NGINX_DYNAMIC, f"{slug}.conf")
    if os.path.exists(conf):
        os.remove(conf)
        log(f"nginx conf removed: {conf}")

    # 4. delete search index
    delete_meili_index(db_filename)

    # 5. registry: mark archived
    entry["enabled"] = False
    entry["status"] = "archived"
    entry["archived_at"] = stamp
    entry["archive_path"] = os.path.relpath(archive_dir, REPO_ROOT)
    save_registry(registry)
    log(f"domain {slug} archived")


def provision_restore(args):
    slug = args.slug
    registry = load_registry()
    entry = next((d for d in registry["domains"] if d["slug"] == slug), None)
    if entry is None:
        raise SystemExit(f"Domain '{slug}' not found")
    if entry.get("status") != "archived":
        raise SystemExit(f"Domain '{slug}' is not archived")
    archive_path = entry.get("archive_path", "")
    src = os.path.join(REPO_ROOT, archive_path) if archive_path else ""
    if not src or not os.path.exists(src):
        raise SystemExit(f"Archive path not found: {src}")
    ddir = os.path.join(DOMAINS_DIR, slug)
    os.makedirs(ddir, exist_ok=True)
    shutil.move(src, ddir)
    log(f"data restored from: {src}")

    conf = os.path.join(NGINX_DYNAMIC, f"{slug}.conf")
    with open(conf, "w", encoding="utf-8") as f:
        f.write(render_nginx_conf(slug, entry["port"]))

    entry["enabled"] = True
    entry["status"] = "pending_start"
    entry.pop("archived_at", None)
    entry.pop("archive_path", None)
    save_registry(registry)

    if not args.no_start:
        start_domain(slug, entry["port"])


def provision_list(_args):
    registry = load_registry()
    for d in registry["domains"]:
        print(f"{d['slug']:<24} port={d['port']:<5} "
              f"enabled={d.get('enabled', True)!s:<5} "
              f"status={d.get('status', 'legacy'):<14} "
              f"dynamic={d.get('dynamic', False)}  {d.get('name', '')}")


def main():
    ap = argparse.ArgumentParser(description="Dynamic domain provisioner")
    sub = ap.add_subparsers(dest="cmd", required=True)

    pc = sub.add_parser("create", help="Create a new dynamic domain")
    pc.add_argument("slug")
    pc.add_argument("--name", help="Display name (default: slug)")
    pc.add_argument("--title", help="Title prefix (default: name or slug)")
    pc.add_argument("--port", type=int, help="Port (default: auto-assign 8770-8799)")
    pc.add_argument("--theme-color", help="Theme color (default #3b4f8c)")
    pc.add_argument("--description", default="")
    pc.add_argument("--ttl-days", type=int, default=90)
    pc.add_argument("--no-start", action="store_true", help="Write files only, do not start container")
    pc.set_defaults(fn=provision_create)

    pa = sub.add_parser("archive", help="Archive (soft-delete) a domain")
    pa.add_argument("slug")
    pa.set_defaults(fn=provision_archive)

    pr = sub.add_parser("restore", help="Restore an archived domain")
    pr.add_argument("slug")
    pr.add_argument("--no-start", action="store_true")
    pr.set_defaults(fn=provision_restore)

    pl = sub.add_parser("list", help="List registered domains")
    pl.set_defaults(fn=provision_list)

    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
